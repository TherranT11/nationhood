-- ═══════════════════════════════════════════════════════════════════════════════
-- SECTORS PHASE 0 — schema, defaults seed, admin-editable per-nation sectors
-- ═══════════════════════════════════════════════════════════════════════════════
-- Purpose:
--   Establishes the per-nation `sectors` table and the `faction_sector_popularity`
--   relation that will eventually replace ideology / momentum / gov_approval as
--   the driver of elections, bill effects, and cascade stats.
--
--   Phase 0 is INVISIBLE TO GAMEPLAY. No game logic reads these tables yet.
--   The admin Sectors tab uses them; everything else is unaffected.
--
-- Conventions:
--   * `sectors.popularity` is conceptually 0.0–10.0 in 0.1 increments.
--     Stored on `faction_sector_popularity.popularity` as integer tenths
--     (0–100). Display as one decimal place.
--   * `sectors.weight` is 1, 2, or 3 (national importance multiplier).
--   * `sectors.base_turnout` is 0.50–1.30 (voting participation multiplier).
--   * Defaults (`is_default = true`) can be renamed/reweighted but never deleted.
--   * Soft-delete via `is_active = false`; preserves popularity history.
--   * `sector_key` is auto-generated by the admin UI from `name` on insert,
--     then locked. Bills will reference sectors by key, not by name.
--
-- Triggers:
--   * After INSERT on nations -> seed_default_sectors(NEW.id)
--   * After INSERT on sectors -> backfill popularity = 0 for all factions in nation
--   * After INSERT on factions -> backfill popularity = 0 for all active sectors
--   * Before UPDATE on either -> refresh updated_at
--
-- All trigger functions are SECURITY DEFINER so they can bypass RLS during
-- normal user-initiated INSERTs.
--
-- Removable:
--   DROP TRIGGER ... ON nations/factions/sectors/faction_sector_popularity;
--   DROP FUNCTION seed_default_sectors, trg_seed_sectors_on_nation_insert,
--     trg_backfill_sector_popularity, trg_backfill_faction_popularity,
--     trg_sectors_set_updated_at;
--   DROP TABLE faction_sector_popularity, sectors;
-- ═══════════════════════════════════════════════════════════════════════════════

BEGIN;

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. TABLES
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS sectors (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    nation_id       uuid NOT NULL REFERENCES nations(id) ON DELETE CASCADE,
    sector_key      text NOT NULL,
    name            text NOT NULL,
    description     text NOT NULL DEFAULT '',
    weight          smallint NOT NULL DEFAULT 1
                        CHECK (weight BETWEEN 1 AND 3),
    base_turnout    numeric(3,2) NOT NULL DEFAULT 1.00
                        CHECK (base_turnout BETWEEN 0.50 AND 1.30),
    is_default      boolean NOT NULL DEFAULT false,
    is_active       boolean NOT NULL DEFAULT true,
    display_order   smallint NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (nation_id, sector_key)
);

CREATE INDEX IF NOT EXISTS idx_sectors_nation_active
    ON sectors (nation_id, is_active);

COMMENT ON TABLE sectors IS
    'Per-nation voter sectors. Populated with 12 defaults on nation creation; admins can add custom sectors via the admin panel.';
COMMENT ON COLUMN sectors.sector_key IS
    'Stable identifier (uppercase, underscored). Bills reference sectors by this key, never by name. Locked after insert.';
COMMENT ON COLUMN sectors.weight IS
    'National importance multiplier 1-3. Used in Total Weighted Popularity = popularity * weight * base_turnout.';
COMMENT ON COLUMN sectors.base_turnout IS
    'Voting participation multiplier 0.50-1.30. Default 1.00.';
COMMENT ON COLUMN sectors.is_active IS
    'Soft-delete flag. Inactive sectors retain their popularity rows for history but are excluded from gameplay calculations.';

CREATE TABLE IF NOT EXISTS faction_sector_popularity (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    faction_id  uuid NOT NULL REFERENCES factions(id) ON DELETE CASCADE,
    sector_id   uuid NOT NULL REFERENCES sectors(id) ON DELETE CASCADE,
    popularity  smallint NOT NULL DEFAULT 0
                    CHECK (popularity BETWEEN 0 AND 100),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (faction_id, sector_id)
);

CREATE INDEX IF NOT EXISTS idx_fsp_faction ON faction_sector_popularity (faction_id);
CREATE INDEX IF NOT EXISTS idx_fsp_sector  ON faction_sector_popularity (sector_id);

COMMENT ON TABLE faction_sector_popularity IS
    'Each faction''s popularity in each sector of its nation, stored as integer tenths (0-100 = 0.0-10.0).';
COMMENT ON COLUMN faction_sector_popularity.popularity IS
    'Integer tenths: 73 means 7.3 displayed popularity. Range 0-100.';

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. SEED FUNCTION — insert the 12 default sectors for one nation
-- ─────────────────────────────────────────────────────────────────────────────

