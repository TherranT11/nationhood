COMMENT ON FUNCTION seed_default_sectors(uuid) IS
    'Inserts the 12 default sectors for the given nation. Idempotent; safe to call multiple times.';

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. TRIGGERS
-- ─────────────────────────────────────────────────────────────────────────────

-- 3a. New nation -> seed 12 default sectors
CREATE OR REPLACE FUNCTION trg_seed_sectors_on_nation_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    PERFORM seed_default_sectors(NEW.id);
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS seed_sectors_on_nation_insert ON nations;
CREATE TRIGGER seed_sectors_on_nation_insert
    AFTER INSERT ON nations
    FOR EACH ROW EXECUTE FUNCTION trg_seed_sectors_on_nation_insert();

-- 3b. New sector -> backfill popularity = 0 for every faction in that nation
CREATE OR REPLACE FUNCTION trg_backfill_sector_popularity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO faction_sector_popularity (faction_id, sector_id, popularity)
    SELECT f.id, NEW.id, 0
    FROM factions f
    WHERE f.nation_id = NEW.nation_id
    ON CONFLICT (faction_id, sector_id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS backfill_sector_popularity ON sectors;
CREATE TRIGGER backfill_sector_popularity
    AFTER INSERT ON sectors
    FOR EACH ROW EXECUTE FUNCTION trg_backfill_sector_popularity();

-- 3c. New faction -> backfill popularity = 0 for every active sector in its nation
CREATE OR REPLACE FUNCTION trg_backfill_faction_popularity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NEW.nation_id IS NULL THEN
        RETURN NEW;
    END IF;

    INSERT INTO faction_sector_popularity (faction_id, sector_id, popularity)
    SELECT NEW.id, s.id, 0
    FROM sectors s
    WHERE s.nation_id = NEW.nation_id AND s.is_active = true
    ON CONFLICT (faction_id, sector_id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS backfill_faction_popularity ON factions;
CREATE TRIGGER backfill_faction_popularity
    AFTER INSERT ON factions
    FOR EACH ROW EXECUTE FUNCTION trg_backfill_faction_popularity();

-- 3d. updated_at maintenance for both tables
CREATE OR REPLACE FUNCTION trg_sectors_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS sectors_set_updated_at ON sectors;
CREATE TRIGGER sectors_set_updated_at
    BEFORE UPDATE ON sectors
    FOR EACH ROW EXECUTE FUNCTION trg_sectors_set_updated_at();

DROP TRIGGER IF EXISTS fsp_set_updated_at ON faction_sector_popularity;
CREATE TRIGGER fsp_set_updated_at
    BEFORE UPDATE ON faction_sector_popularity
    FOR EACH ROW EXECUTE FUNCTION trg_sectors_set_updated_at();

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. RLS POLICIES — public read, admin-only write
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE sectors ENABLE ROW LEVEL SECURITY;
ALTER TABLE faction_sector_popularity ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow select for all" ON sectors;
CREATE POLICY "Allow select for all" ON sectors
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admin writes" ON sectors;
CREATE POLICY "Admin writes" ON sectors
    FOR ALL TO authenticated
    USING (is_admin())
    WITH CHECK (is_admin());

DROP POLICY IF EXISTS "Allow select for all" ON faction_sector_popularity;
CREATE POLICY "Allow select for all" ON faction_sector_popularity
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admin writes" ON faction_sector_popularity;
CREATE POLICY "Admin writes" ON faction_sector_popularity
    FOR ALL TO authenticated
    USING (is_admin())
    WITH CHECK (is_admin());

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. BACKFILL — seed defaults for every existing nation
-- ─────────────────────────────────────────────────────────────────────────────

DO $$
DECLARE
    n_id uuid;
BEGIN
    FOR n_id IN SELECT id FROM nations LOOP
        PERFORM seed_default_sectors(n_id);
    END LOOP;
END $$;

COMMIT;
