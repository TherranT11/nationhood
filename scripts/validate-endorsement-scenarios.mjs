import fs from 'node:fs';
import { execSync } from 'node:child_process';
import { runElectionSimulation } from '../js/game/election-simulation.js';

const EXCLUDES = ["-g '!docs/endorsement-validation-report.md'", "-g '!scripts/validate-endorsement-scenarios.mjs'"];

function rgCount(pattern, globs = []) {
  const globArgs = globs.map(g => `-g '${g}'`).join(' ');
  const cmd = `rg -n --no-heading -S ${globArgs} ${EXCLUDES.join(' ')} "${pattern.replace(/"/g, '\\"')}" . || true`;
  const out = execSync(cmd, { encoding: 'utf8', shell: '/bin/bash' }).trim();
  if (!out) return { count: 0, lines: [] };
  const lines = out.split('\n');
  return { count: lines.length, lines };
}

function runoffScenarios() {
  const blocs = [
    { id: 'b1', bloc_name: 'Bloc A', voter_count: 1000, ideology_1: 'LIBERTY', is_active: true },
    { id: 'b2', bloc_name: 'Bloc B', voter_count: 1000, ideology_1: 'EQUALITY', is_active: true }
  ];
  const p = (id, le, tp) => ({ id, faction_name: id, axes: { liberty_equality: le, tradition_progress: tp, security_freedom: 0, globalism_nationalism: 0, individualism_collectivism: 0 } });

  const partiesRunoff = [p('c1', 70, 20), p('c2', -70, -20), p('c3', 0, 0)];
  const approvalsRunoff = { b1: { c1: 46, c2: 44, c3: 45 }, b2: { c1: 45, c2: 46, c3: 44 } };
  const round1 = runElectionSimulation(blocs, partiesRunoff, 0, approvalsRunoff);
  const sorted1 = Object.entries(round1.votes).sort((a, b) => b[1] - a[1]);
  const topPct1 = round1.totalVotesCast ? (sorted1[0][1] / round1.totalVotesCast) * 100 : 0;

  const partiesNoRunoff = [p('c1', 80, 20), p('c2', -80, -20)];
  const approvalsNo = { b1: { c1: 80, c2: 20 }, b2: { c1: 78, c2: 22 } };
  const roundNo = runElectionSimulation(blocs, partiesNoRunoff, 0, approvalsNo);
  const sortedNo = Object.entries(roundNo.votes).sort((a, b) => b[1] - a[1]);
  const topPctNo = roundNo.totalVotesCast ? (sortedNo[0][1] / roundNo.totalVotesCast) * 100 : 0;

  const voidRound = runElectionSimulation([], partiesNoRunoff, 0, {});

  return {
    runoffTriggered: topPct1 <= 50 && partiesRunoff.length > 2,
    topPct1,
    noRunoff: topPctNo > 50 || partiesNoRunoff.length <= 2,
    topPctNo,
    voidHandled: voidRound.totalVotesCast === 0 && voidRound.totalAbstentions === 0
  };
}

const coalitionDebt = rgCount('coalition debt|coalition_debt', ['*.sql', '*.js', '*.html', '*.md']);
const npcRefs = rgCount('\\bis_npc\\b|\\bNPC\\b|\\bnpc\\b', ['*.sql', '*.js', '*.html', '*.md']);
const snappedSignal = rgCount('snap', ['js/game/elections.js', 'politics.html', '*.sql']);
const endorseFlowSignals = [
  rgCount('endorse', ['*.sql', '*.js', '*.html']).count,
  rgCount('switch endorsement|change endorsement', ['*.sql', '*.js', '*.html']).count,
  rgCount('pol-endorse-btn', ['politics.html']).count
];
const runoff = runoffScenarios();

